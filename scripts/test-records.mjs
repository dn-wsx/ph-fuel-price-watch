import assert from 'node:assert/strict';
import { appendRecord, observePublication, publishedTrack, walkForward } from './records.mjs';

const fuels = { gasoline: { value: -4, low: -5, high: -3, source: 'singapore', daysOfData: 2 } };
const log = {};
const first = { target: '2026-11-17', generatedAt: '2026-11-11T08:00:00Z', model: 2, basis: 'singapore', fuels, sourceDates: { MOPS92: '2026-11-10' } };
appendRecord(log, first, '2');
appendRecord(log, { ...first, generatedAt: '2026-11-11T10:00:00Z', fuels: { gasoline: { ...fuels.gasoline, value: -4.5 } } }, '2');
assert.equal(log[first.target].records.length, 2);
assert.equal(log[first.target].records[0].fuels.gasoline.value, -4);
assert.equal(publishedTrack(log, { [first.target]: { gasoline: -5 } }).weeks, 0);
assert.equal(observePublication(log, { ...first, fuels: { gasoline: { ...fuels.gasoline, value: 99 } } }, '2026-11-11T09:00:00Z'), false);
assert.equal(observePublication(log, { ...first, model: 99 }, '2026-11-11T09:00:00Z'), false);
assert.equal(observePublication(log, first, '2026-11-11T09:00:00Z'), true);
assert.equal(observePublication(log, first, '2026-11-11T10:00:00Z'), true);
assert.equal(log[first.target].records[0].publishedObservedAt, '2026-11-11T09:00:00Z');
const track = publishedTrack(log, { [first.target]: { gasoline: -5 } });
assert.equal(track.weeks, 1);
assert.deepEqual(track.stages[0].metrics.gasoline, { n: 1, mae: 1, bias: 1, directionCorrect: 1, covered: 1, intervalN: 1 });
assert.equal(track.stages[0].metrics.diesel.n, 0);
assert.equal(publishedTrack(log, { [first.target]: { gasoline: -5, provisional: true } }).weeks, 0);
assert.equal(publishedTrack(log, { [first.target]: { gasoline: -5, diesel: 1, fuelSources: { gasoline: { kind: 'manual', provisional: false }, diesel: { kind: 'news', provisional: true } } } }).stages[0].metrics.gasoline.n, 1);
const late = structuredClone(log);
late[first.target].records[0].publishedObservedAt = '2026-11-17T00:00:00Z';
assert.equal(publishedTrack(late, { [first.target]: { gasoline: -5 } }).weeks, 0);
assert.equal(publishedTrack({ [first.target]: { snapshots: { 2: { gasoline: -4 } } } }, { [first.target]: { gasoline: -5 } }).weeks, 0);
const pairs = Array.from({ length: 10 }, (_, i) => [`2026-09-${String(i + 1).padStart(2, '0')}`, i + 1, (i + 1) * 0.8]);
const evaluation = walkForward(pairs);
const changed = walkForward(pairs.map((p, i) => i === 9 ? [p[0], p[1], 100] : p));
assert.deepEqual(evaluation.predictions.slice(0, 9), changed.predictions.slice(0, 9));
assert.equal(evaluation.predictions[9].value, changed.predictions[9].value);
assert.equal(evaluation.n, 10);
assert.ok(Number.isFinite(evaluation.mae));
console.log('Immutable records, verified-publication scoring and walk-forward tests passed');
